CREATE TABLE PIREP_ANALYSIS_FACTORS (
 ID               INTEGER UNSIGNED NOT NULL,
 SEQ              TINYINT UNSIGNED NOT NULL,
 FACTOR           VARCHAR(160) CHARACTER SET utf8mb4 NOT NULL,
 PRIMARY KEY (ID, SEQ),
 FOREIGN KEY (ID) REFERENCES PIREP_ANALYSIS(ID) ON DELETE CASCADE ON UPDATE CASCADE
) CHARACTER SET latin1 COMPRESSION="LZ4";