CREATE TABLE PIREP_ANALYSIS (
 ID             INTEGER UNSIGNED NOT NULL,
 CREATED        DATETIME NOT NULL,
 SAFETY         SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 COMFORT        SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 SUMMARY        TEXT CHARACTER SET utf8mb4 NOT NULL,
 PRIMARY KEY (ID),
 FOREIGN KEY (ID) REFERENCES PIREPS(ID) ON DELETE CASCADE ON UPDATE CASCADE
) CHARACTER SET latin1 COMPRESSION="LZ4";