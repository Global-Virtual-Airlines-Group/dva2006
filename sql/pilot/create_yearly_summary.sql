CREATE TABLE YEARLY_SUMMARY (
 ID               INTEGER UNSIGNED NOT  NULL,
 YEAR             SMALLINT UNSIGNED NOT NULL,
 CREATED          DATETIME NOT NULL,
 IN_TOKENS        INTEGER UNSIGNED NOT NULL DEFAULT 0,
 OUT_TOKENS       INTEGER UNSIGNED NOT NULL DEFAULT 0,
 GEN_TIME         INTEGER UNSIGNED NOT NULL DEFAULT 0,
 SUMMARY          TEXT CHARACTER SET utf8mb4 NOT NULL,
 PRIMARY KEY (ID, YEAR),
 FOREIGN KEY (ID) REFERENCES PILOTS(ID) ON UPDATE CASCADE ON DELETE CASCADE
) CHARACTER SET latin1 COMPRESSION="LZ4";