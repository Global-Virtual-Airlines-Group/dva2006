CREATE TABLE finance.SHARES (
 YEAR               SMALLINT UNSIGNED NOT NULL,
 OWNER_ID           INTEGER UNSIGNED NOT NULL,
 CNT                SMALLINT UNSIGNED NOT NULL,
 PRIMARY KEY (YEAR, OWNER_ID),
 FOREIGN KEY (YEAR) REFERENCES finance.SHARE_PRICE(YEAR),
 FOREIGN KEY (OWNER_ID) REFERENCES common.USERDATA(ID) ON UPDATE CASCADE
) CHARACTER SET latin1;